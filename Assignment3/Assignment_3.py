from flask import Flask, render_template, request, redirect, url_for, session
import json
import random
import os

#Access the questions from the JSON file
with open("questions.json") as file:
    ALL_QUESTIONS = json.load(file)

QUESTIONS_PER_QUIZ = 5
num_questions = min(QUESTIONS_PER_QUIZ, len(ALL_QUESTIONS))

app = Flask(__name__)
app.secret_key = os.environ.get("SECRET_KEY", "development-only-secret-key")

'''
The following 3 functions and a few other pieces of code were generated by copilot under the prompt: 
"Use sessions to check if a user has already visited the quiz game. 
If so, welcome them back and show them their score history. 
If it's their first visit, ask them for their name and 
save it in a session which will be used to identify them in subsequent visits. 
Also use sessions to track the user's quiz score history."
'''

def start_quiz():
    session["quiz_score"] = 0
    session["question_number"] = 0
    session["quiz_questions"] = random.sample(list(ALL_QUESTIONS.items()), num_questions)
    session["quiz_active"] = True

def record_quiz_score():
    if not session.get("quiz_active"):
        return

    history = session.get("score_history", [])
    history.append({
        "score": session["quiz_score"],
        "num_questions": num_questions
    })
    session["score_history"] = history
    session["quiz_active"] = False

def get_quiz_state():
    if not session.get("quiz_active"):
        start_quiz()

#index.html
@app.route('/', methods=["GET", "POST"])
def index():
    if request.method == "POST":
        name = request.form.get("name", "").strip()
        if name:
            session["name"] = name
            session.setdefault("score_history", [])
        return redirect(url_for("index"))

    session.pop("quiz_active", None)
    return render_template(
        'index.html',
        name=session.get("name"),
        score_history=session.get("score_history", [])
    )

#quiz.html
@app.route("/quiz", methods=["GET", "POST"])
def quiz():
    if "name" not in session:
        return redirect(url_for("index"))

    get_quiz_state()
    questions = session["quiz_questions"]
    question_number = session["question_number"]
    score = session["quiz_score"]

    if request.method == "POST":
        question_data = questions[question_number][1]
        correct_answer = question_data[0]

        if request.form.get("answer") == correct_answer:
            score += 1

        session["quiz_score"] = score
        question_number += 1
        session["question_number"] = question_number

    if question_number >= len(questions):
        record_quiz_score()
        return redirect(url_for("results"))

    question_data = questions[question_number][1]

    #Randomize the options for each question
    options = list(question_data)
    random.shuffle(options)

    return render_template("quiz.html",
        name=session["name"],
        question_number=question_number,
        question=questions[question_number][0],
        options=options,
        score=score,
        num_questions=num_questions)

#results.html
@app.route('/results', methods=["GET", "POST"])
def results():
    if "name" not in session:
        return redirect(url_for("index"))

    return render_template(
        'results.html',
        name=session["name"],
        score=session.get("quiz_score", 0),
        num_questions=num_questions,
        score_history=session.get("score_history", [])
    )

@app.route("/logout")
def logout():
    session.pop("name", None)
    session.pop("quiz_score", None)
    session.pop("question_number", None)
    session.pop("quiz_questions", None)
    session.pop("quiz_active", None)
    return redirect(url_for("index"))

def main():
    app.run(debug=True)

if __name__ == "__main__":
    main()
