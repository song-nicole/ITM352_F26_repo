#Establishes global variables for each session
def start_quiz():
    session["quiz_score"] = 0
    session["question_number"] = 0
    session["quiz_questions"] = random.sample(list(ALL_QUESTIONS.items()), num_questions)
    session["quiz_active"] = True
    session["hint_used"] = False
    session["hint_question"] = None
    session["quiz_answers"] = []

def record_quiz_score():
    if not session.get("quiz_active"):
        return

    score_histories = load_score_histories()
    name = session["name"]

    history = score_histories.setdefault(name, [])

    history.append({
        "score": session["quiz_score"],
        "num_questions": num_questions
    })

    save_score_histories(score_histories)
    session["quiz_active"] = False

def get_quiz_state():
    if not session.get("quiz_active"):
        start_quiz()


#index.html
@app.route('/', methods=["GET", "POST"])
def index():
    if request.method == "POST":
        #Ask the user to sign in and decide whether to start a new quiz or continue an existing one
        name = request.form.get("name", "").strip()
        if name:
            session["name"] = name

        score_histories = load_score_histories()

        if name not in score_histories:
            score_histories[name] = []
            save_score_histories(score_histories)

        return redirect(url_for("index"))

    session.pop("quiz_active", None)
    return render_template(
    "index.html",
    name=session.get("name"),
    score_history=load_score_histories().get(session.get("name"), [])
)

#quiz.html
@app.route("/quiz", methods=["GET", "POST"])
def quiz():
    if "name" not in session:
        return redirect(url_for("index"))

    get_quiz_state()
    questions = session["quiz_questions"]
    question_number = session["question_number"]
    score = session["quiz_score"]
    answer_error = None

    if request.method == "POST":
        #Checks if the user used a hint
        if request.form.get("hint") == "request":
            if not session.get("hint_used"):
                session["hint_used"] = True
                session["hint_question"] = question_number
        else:
            selected_answer = request.form.get("answer")

            #Ensures that the user selects an answer before submitting
            if selected_answer is not None:
                question_data = questions[question_number][1]
                correct_answer = question_data[0]
                is_correct = selected_answer == correct_answer

                if is_correct:
                    score += 1

                #Allows the user to review their answers after the quiz is completed
                quiz_answers = session.setdefault("quiz_answers", [])
                quiz_answers.append({
                    "question": questions[question_number][0],
                    "selected_answer": selected_answer,
                    "correct_answer": correct_answer,
                    "is_correct": is_correct
                })
                session["quiz_answers"] = quiz_answers

                session["quiz_score"] = score
                question_number += 1
                session["question_number"] = question_number
                session["hint_question"] = None
            else:
                answer_error = "***Please select an answer before submitting."

    #Limits the number of questions asked per quiz
    if question_number >= len(questions):
        record_quiz_score()
        return redirect(url_for("results"))

    question_data = questions[question_number][1]

    #Randomize the options for each question
    options = list(question_data)
    random.shuffle(options)

    hint = None
    if session.get("hint_used") and session.get("hint_question") == question_number:
        hint = HINTS[questions[question_number][0]]

    return render_template("quiz.html",
        name=session["name"],
        question_number=question_number,
        question=questions[question_number][0],
        options=options,
        score=score,
        num_questions=num_questions,
        hint=hint,
        hint_used=session.get("hint_used", False),
        answer_error=answer_error)

#results.html
@app.route('/results', methods=["GET", "POST"])
def results():
    if "name" not in session:
        return redirect(url_for("index"))

    return render_template(
        'results.html',
        name=session["name"],
        score=session.get("quiz_score", 0),
        num_questions=num_questions,
        score_history=load_score_histories().get(session.get("name"), [])
    )

#answers.html
@app.route("/answers")
def answers():
    if "name" not in session:
        return redirect(url_for("index"))

    return render_template(
        "answers.html",
        name=session["name"],
        quiz_answers=session.get("quiz_answers", [])
    )

#Allows the user to log out
@app.route("/logout")
def logout():
    session.pop("name", None)
    session.pop("quiz_score", None)
    session.pop("question_number", None)
    session.pop("quiz_questions", None)
    session.pop("quiz_active", None)
    return redirect(url_for("index"))

def main():
    app.run(debug=True)

if __name__ == "__main__":
    main()
